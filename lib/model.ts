// Token Radar — model "radar-2" for token-radar-01.
//
// Reads the sealed DefiLlama snapshot and ranks every protocol that records
// no token and is not a wrapped / staked / bridged product of a token that
// already trades. The board is the whole such universe in the snapshot
// (198 rows: the 40-protocol watchlist plus 158 early protocols below the
// $50M floor), not an arbitrary TVL cut.
//
// Implied value is one function of the snapshot's own figures, the same
// function for every protocol; no protocol name is ever special-cased:
//
//   implied = round( tvl_usd
//                     * BASE_MULTIPLE
//                     * growthMult
//                     * maturityMult
//                     * chainMult )
//
//   growthMult   = 1 + clamp(change_7d, -60, 120) / 100 * GROWTH_WEIGHT
//   maturityMult = 0.55 + min(age_days, 1460) / 1460 * 0.45
//                  (age = days since DefiLlama first listed the protocol;
//                   unknown age uses 365 days)
//   chainMult    = 1 + min(chains - 1, 4) * CHAIN_BONUS
//                  (a protocol live on more chains reaches more farmers)
//
// Farm plans are derived from the same record (category, chains, TVL tier,
// age): the action, the capital, the hold and every cost and time. A step
// is one string, "Action. Cost: ... Time: ...", 20..600 characters.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_bonus: number;
  chain_cap: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.6,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.55,
  maturity_range: 0.45,
  maturity_days: 1460,
  unknown_age_days: 365,
  chain_bonus: 0.03,
  chain_cap: 4,
};

export const MODEL_VERSION = 'radar-2';
export const LIVE_ROWS = 24;

